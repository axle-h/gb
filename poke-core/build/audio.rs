//! The three copies of the sound data, assembled from `audio.asm` and the macros in
//! `macros/scripts/audio.asm`, and the tables that name a sound by its header.
//!
//! A bank's data is laid out from `$4000` in the linker's order with the engine's code left out, so
//! the header tables and sound effects, which come before any code, sit where the cartridge has them
//! and a sound id is the same header row. Music, after the code, starts earlier here than there.

use std::collections::HashMap;
use std::fmt::Write;
use super::asm::{Asm, Row};

/// Where each bank's header table starts, and what `music_const` subtracts.
const HEADERS: i64 = 0x4000;

struct Bank {
    rom_bank: u8,
    bytes: Vec<u8>,
    labels: Vec<(String, u16)>,
    /// Where a `dw label` sits, for the oracle to relocate.
    pointers: Vec<u16>,
}

pub fn write(asm: &mut Asm) -> String {
    let mut out = String::from("// Generated by build.rs from vendor/pokered/audio.\n\n");
    let layout = layout(asm);
    let sections = sections(asm);

    let banks: Vec<Bank> = (1..=3).map(|n| {
        let rom_bank = layout.iter().find(|(_, names)| names.contains(&format!("Sound Effect Headers {n}")))
            .unwrap_or_else(|| panic!("no bank holds the headers of audio {n}")).0;
        let names = &layout.iter().find(|(bank, _)| *bank == rom_bank).unwrap().1;
        let rows: Vec<&[Row]> = names.iter().filter_map(|name| sections.get(name.as_str()).map(Vec::as_slice)).collect();
        assemble(asm, rom_bank, &rows)
    }).collect();

    // What `music_const` evaluates: a header label's address, each bank's table starting at `$4000`.
    asm.set("SFX_Headers_1", HEADERS);
    for bank in &banks {
        for (name, address) in &bank.labels {
            if !name.contains('.') {
                asm.set(name, *address as i64);
            }
        }
    }

    writeln!(out, "pub static AUDIO_BANKS: [AudioBankData; 3] = [").unwrap();
    for bank in &banks {
        let labels: Vec<String> = bank.labels.iter().map(|(name, at)| format!("({name:?}, {at})")).collect();
        writeln!(out, "    AudioBankData {{ rom_bank: {}, bytes: &{:?}, labels: &[{}], pointers: &{:?} }},",
            bank.rom_bank, bank.bytes, labels.join(", "), bank.pointers).unwrap();
    }
    writeln!(out, "];").unwrap();

    let pitches: Vec<String> = asm.file_rows("audio/notes.asm").iter().map(|row| {
        assert_eq!((row.op.as_str(), row.args.len()), ("dw", 1), "{row:?}");
        asm.eval(&row.args[0]).to_string()
    }).collect();
    assert_eq!(pitches.len() as i64, asm.eval("NUM_NOTES"));
    writeln!(out, "pub const PITCHES: [u16; {}] = [{}];", pitches.len(), pitches.join(", ")).unwrap();

    writeln!(out, "#[allow(dead_code)]\npub mod sound {{").unwrap();
    let mut names: Vec<String> = asm.file_rows("constants/music_constants.asm").into_iter()
        .filter(|row| row.op == "music_const").map(|row| row.args[0].clone()).collect();
    names.extend(["NOISE_INSTRUMENTS_START", "NOISE_INSTRUMENTS_END", "CRY_SFX_START", "CRY_SFX_END", "MAX_SFX_ID_1",
        "MAX_SFX_ID_2", "MAX_SFX_ID_3", "BATTLE_SFX_START", "BATTLE_SFX_END", "SFX_STOP_ALL_MUSIC"].map(String::from));
    for name in names {
        writeln!(out, "    pub const {name}: u8 = {};", asm.byte(&name)).unwrap();
    }
    writeln!(out, "}}").unwrap();

    let bank_of = |arg: &str| -> u8 {
        let label = arg.strip_prefix("BANK(").and_then(|rest| rest.strip_suffix(')')).unwrap_or_else(|| panic!("`{arg}` is not a BANK()"));
        banks.iter().find(|bank| bank.labels.iter().any(|(name, _)| name == label)).unwrap_or_else(|| panic!("no bank holds {label}")).rom_bank
    };

    let rows = asm.rows("data/maps/songs.asm", "MapSongBanks");
    let items: Vec<String> = rows.iter().map(|row| {
        assert_eq!((row.op.as_str(), row.args.len()), ("db", 2), "{row:?}");
        format!("({}, {})", asm.byte(&row.args[0]), bank_of(&row.args[1]))
    }).collect();
    assert_eq!(items.len() as i64, asm.eval("NUM_MAPS"));
    writeln!(out, "pub const MAP_SONG_BANKS: [(u8, u8); {}] = [{}];", items.len(), items.join(", ")).unwrap();

    let rows = asm.rows("audio/pokedex_rating_sfx.asm", "PokedexRatingSfxPointers");
    let items: Vec<String> = rows.iter().map(|row| {
        assert_eq!((row.op.as_str(), row.args.len()), ("db", 2), "{row:?}");
        format!("({}, {})", asm.byte(&row.args[0]), bank_of(&row.args[1]))
    }).collect();
    writeln!(out, "pub const POKEDEX_RATING_SFX: [(u8, u8); {}] = [{}];", items.len(), items.join(", ")).unwrap();

    // The base cry as the sound it names, which `mon_cry` stores as its distance from the first.
    let rows = asm.rows("data/pokemon/cries.asm", "CryData");
    let items: Vec<String> = rows.iter().map(|row| {
        assert_eq!((row.op.as_str(), row.args.len()), ("mon_cry", 3), "{row:?}");
        format!("({}, {}, {})", asm.byte(&row.args[0]), asm.byte(&row.args[1]), asm.byte(&row.args[2]))
    }).collect();
    writeln!(out, "pub const CRY_DATA: [(u8, u8, u8); {}] = [{}];", items.len(), items.join(", ")).unwrap();

    // Past `NUM_ATTACKS` there is one more row, which a sound byte of `NUM_ATTACKS` reads.
    let rows = asm.rows("data/moves/sfx.asm", "MoveSoundTable");
    let items: Vec<String> = rows.iter().map(|row| {
        assert_eq!((row.op.as_str(), row.args.len()), ("db", 3), "{row:?}");
        format!("({}, {}, {})", asm.byte(&row.args[0]), asm.byte(&row.args[1]), asm.byte(&row.args[2]))
    }).collect();
    writeln!(out, "pub const MOVE_SOUND_TABLE: [(u8, u8, u8); {}] = [{}];", items.len(), items.join(", ")).unwrap();
    out
}

/// `layout.link`'s switchable banks, each with its sections in order.
fn layout(asm: &Asm) -> Vec<(u8, Vec<String>)> {
    let mut banks: Vec<(u8, Vec<String>)> = Vec::new();
    let mut current = false;
    for line in asm.lines("layout.link") {
        let line = line.trim();
        if let Some(name) = line.strip_prefix('"').and_then(|rest| rest.strip_suffix('"')) {
            if current {
                banks.last_mut().unwrap().1.push(name.to_string());
            }
        } else if let Some(bank) = line.strip_prefix("ROMX $") {
            banks.push((u8::from_str_radix(bank, 16).unwrap(), Vec::new()));
            current = true;
        } else if !line.is_empty() && !line.starts_with("org") {
            current = false;
        }
    }
    banks
}

/// `audio.asm`'s rows, each section's apart.
fn sections(asm: &mut Asm) -> HashMap<String, Vec<Row>> {
    let mut sections: HashMap<String, Vec<Row>> = HashMap::new();
    let mut current = None;
    for row in asm.file("audio.asm") {
        if row.op.eq_ignore_ascii_case("SECTION") {
            let name = row.args[0].trim_matches('"').to_string();
            sections.entry(name.clone()).or_default();
            current = Some(name);
        } else {
            sections.get_mut(current.as_ref().expect("a row before any section")).unwrap().push(row);
        }
    }
    sections
}

fn is_label(row: &Row) -> bool {
    row.args.is_empty() && (row.op.ends_with(':') || row.op.starts_with('.'))
}

/// A label row's name, a local one qualified by the global label it follows.
fn label_name(row: &Row, scope: &str) -> String {
    let name = row.op.trim_end_matches(':');
    match name.starts_with('.') {
        true => format!("{scope}{name}"),
        false => name.to_string(),
    }
}

/// How many bytes an audio macro assembles to, or `None` for anything else.
fn size(op: &str, args: usize) -> Option<usize> {
    Some(match op {
        "channel_count" => 0,
        "note" | "rest" | "drum_speed" | "octave" | "toggle_perfect_pitch" | "execute_music" | "sound_ret" | "drum_note_short" => 1,
        "pitch_sweep" | "drum_note" | "note_type" | "duty_cycle" | "stereo_panning" | "unknownmusic0xef" | "volume"
        | "duty_cycle_pattern" => 2,
        "channel" | "vibrato" | "pitch_slide" | "tempo" | "sound_call" | "noise_note" => 3,
        "sound_loop" | "square_note" => 4,
        "db" => args,
        "dw" => 2 * args,
        "dn" => args.div_ceil(2),
        _ => return None,
    })
}

/// One bank's sections in order: the data ones whole, and from the engine's code only a label a
/// channel is pointed at, which is one whose next row is a sound command.
fn assemble(asm: &Asm, rom_bank: u8, sections: &[&[Row]]) -> Bank {
    let data = |row: &Row| is_label(row) || size(&row.op, row.args.len()).is_some();
    let command = |row: &Row| !is_label(row) && !matches!(row.op.as_str(), "db" | "dw" | "dn") && size(&row.op, 0).is_some();
    let kept: Vec<&Row> = sections.iter().flat_map(|rows| match rows.iter().all(data) {
        true => rows.iter().collect::<Vec<_>>(),
        false => rows.windows(2).filter(|pair| is_label(&pair[0]) && !pair[0].op.starts_with('.') && command(&pair[1]))
            .flat_map(|pair| [&pair[0], &pair[1]]).collect(),
    }).collect();

    // Every macro's size is fixed, so the labels are known before any pointer is resolved.
    let mut labels = Vec::new();
    let (mut at, mut scope) = (HEADERS as usize, String::new());
    for row in &kept {
        if is_label(row) {
            let name = label_name(row, &scope);
            if !row.op.starts_with('.') {
                scope = name.clone();
            }
            labels.push((name, u16::try_from(at).unwrap()));
        } else {
            at += size(&row.op, row.args.len()).unwrap();
        }
    }
    let addresses: HashMap<&str, u16> = labels.iter().map(|(name, at)| (name.as_str(), *at)).collect();

    let mut bytes: Vec<u8> = Vec::new();
    let mut pointers = Vec::new();
    let (mut scope, mut channels) = (String::new(), 0);
    for row in &kept {
        if is_label(row) {
            if !row.op.starts_with('.') {
                scope = label_name(row, "");
            }
            continue;
        }
        let arg = |i: usize| asm.eval(&row.args[i]);
        let byte = |value: i64| u8::try_from(value).unwrap_or_else(|_| panic!("{row:?} makes {value}"));
        let dn = |high: i64, low: i64| byte(high << 4 | low);
        // Fade and sweep are sign and magnitude.
        let signed = |value: i64| if value < 0 { 0b1000 | -value } else { value };
        let cmd = |name: &str| asm.eval(name);
        let mut label = |bytes: &mut Vec<u8>, name: &str| {
            let full = match name.starts_with('.') {
                true => format!("{scope}{name}"),
                false => name.to_string(),
            };
            let target = *addresses.get(full.as_str()).unwrap_or_else(|| panic!("{row:?}: no {full} in bank {rom_bank:02X}"));
            pointers.push(u16::try_from(HEADERS as usize + bytes.len()).unwrap());
            bytes.extend(target.to_le_bytes());
        };
        let before = bytes.len();
        match row.op.as_str() {
            "channel_count" => channels = arg(0) - 1,
            "channel" => {
                bytes.push(dn(channels << 2, arg(0) - 1));
                label(&mut bytes, &row.args[1]);
                channels = 0;
            }
            "pitch_sweep" => bytes.extend([byte(cmd("pitch_sweep_cmd")), dn(arg(0), signed(arg(1)))]),
            "square_note" => {
                bytes.extend([byte(cmd("square_note_cmd") | arg(0)), dn(arg(1), signed(arg(2)))]);
                bytes.extend(u16::try_from(arg(3)).unwrap().to_le_bytes());
            }
            "noise_note" => bytes.extend([byte(cmd("noise_note_cmd") | arg(0)), dn(arg(1), signed(arg(2))), byte(arg(3))]),
            "note" | "drum_note_short" => bytes.push(dn(arg(0), arg(1) - 1)),
            "drum_note" => bytes.extend([byte(cmd("drum_note_cmd") | (arg(1) - 1)), byte(arg(0))]),
            "rest" => bytes.push(byte(cmd("rest_cmd") | (arg(0) - 1))),
            "note_type" => bytes.extend([byte(cmd("note_type_cmd") | arg(0)), dn(arg(1), signed(arg(2)))]),
            "drum_speed" => bytes.push(byte(cmd("drum_speed_cmd") | arg(0))),
            "octave" => bytes.push(byte(cmd("octave_cmd") | (8 - arg(0)))),
            "toggle_perfect_pitch" => bytes.push(byte(cmd("toggle_perfect_pitch_cmd"))),
            "vibrato" => bytes.extend([byte(cmd("vibrato_cmd")), byte(arg(0)), dn(arg(1), arg(2))]),
            "pitch_slide" => bytes.extend([byte(cmd("pitch_slide_cmd")), byte(arg(0) - 1), dn(8 - arg(1), arg(2))]),
            "duty_cycle" => bytes.extend([byte(cmd("duty_cycle_cmd")), byte(arg(0))]),
            "tempo" => bytes.extend([byte(cmd("tempo_cmd")), byte(arg(0) >> 8), byte(arg(0) & 0xFF)]),
            "stereo_panning" => bytes.extend([byte(cmd("stereo_panning_cmd")), dn(arg(0), arg(1))]),
            "unknownmusic0xef" => bytes.extend([byte(cmd("unknownmusic0xef_cmd")), byte(arg(0))]),
            "volume" => bytes.extend([byte(cmd("volume_cmd")), dn(arg(0), arg(1))]),
            "execute_music" => bytes.push(byte(cmd("execute_music_cmd"))),
            "duty_cycle_pattern" => bytes.extend([byte(cmd("duty_cycle_pattern_cmd")), byte(arg(0) << 6 | arg(1) << 4 | arg(2) << 2 | arg(3))]),
            "sound_call" => {
                bytes.push(byte(cmd("sound_call_cmd")));
                label(&mut bytes, &row.args[0]);
            }
            "sound_loop" => {
                bytes.extend([byte(cmd("sound_loop_cmd")), byte(arg(0))]);
                label(&mut bytes, &row.args[1]);
            }
            "sound_ret" => bytes.push(byte(cmd("sound_ret_cmd"))),
            "db" => bytes.extend(row.args.iter().map(|arg| asm.byte(arg))),
            "dw" => row.args.iter().for_each(|name| label(&mut bytes, name)),
            "dn" => bytes.extend(row.args.chunks(2).map(|pair| dn(asm.eval(&pair[0]), pair.get(1).map_or(0, |low| asm.eval(low))))),
            _ => panic!("{row:?} is not sound data"),
        }
        assert_eq!(bytes.len() - before, size(&row.op, row.args.len()).unwrap(), "{row:?}");
    }
    Bank { rom_bank, bytes, labels, pointers }
}
