/// `rows` split at the labels it reads through, a local one or one in a file it INCLUDEs, which it
/// hands back as a row of their own: the rows before the first, and each label's own.
fn labelled(rows: &[Row]) -> (&[Row], std::collections::HashMap<&str, &[Row]>) {
    let is_label = |row: &Row| row.args.is_empty() && row.op.ends_with(':');
    let first = rows.iter().position(is_label).unwrap_or(rows.len());
    let mut labels = std::collections::HashMap::new();
    let mut at = first;
    while at < rows.len() {
        let end = rows[at + 1..].iter().position(is_label).map_or(rows.len(), |n| at + 1 + n);
        labels.insert(rows[at].op.trim_end_matches(':'), &rows[at + 1..end]);
        at = end;
    }
    (&rows[..first], labels)
}

/// Every row's arguments as the bytes `op` assembles them to: `dc` packs four two-bit crumbs to a
/// byte, and any other op is a `db` whose arguments are the row's fields.
fn bytes(asm: &Asm, rows: &[Row], op: &str) -> Vec<Vec<u8>> {
    rows.iter().map(|row| {
        assert_eq!(row.op, op, "{row:?}");
        let values: Vec<u8> = row.args.iter().map(|arg| asm.byte(arg)).collect();
        match op {
            "dc" => values.chunks_exact(4).map(|crumbs| crumbs.iter().fold(0, |byte, &crumb| byte << 2 | crumb)).collect(),
            _ => values,
        }
    }).collect()
}

/// A name list's entries, `li` or `dname`, as the text between their quotes. The padding `dname`
/// adds and the terminator `li` does are the cartridge's layout, not the name.
fn names(rows: &[Row]) -> impl Iterator<Item = &str> {
    rows.iter().filter(|row| !matches!(row.op.as_str(), "list_start" | "assert_list_length")).map(|row| {
        assert!(matches!(row.op.as_str(), "li" | "dname"), "{row:?}");
        text(&row.args[0])
    })
}

/// A string argument's text.
fn text(arg: &str) -> &str {
    let inner = arg.strip_prefix('"').and_then(|text| text.strip_suffix('"')).unwrap_or_else(|| panic!("`{arg}` is not a string"));
    assert!(!inner.contains(['"', '\\']), "`{arg}` is more than one string");
    inner
}

/// The values of a stateful packing macro's entries, `start` and `end` left out.
fn array_macro<'a>(asm: &'a Asm, rows: &'a [Row], start: &str, entry: &'a str, end: &str) -> impl Iterator<Item = i64> + 'a {
    let (first, rows) = rows.split_first().expect("an empty array");
    let (last, rows) = rows.split_last().expect("an empty array");
    assert_eq!((first.op.as_str(), last.op.as_str()), (start, end));
    rows.iter().map(move |row| {
        assert_eq!(row.op, entry, "{row:?}");
        asm.eval(&row.args[0])
    })
}

/// One species' base data. The picture's size and pointers are graphics and are not read here.
fn base_stats(asm: &Asm, entry: &[Row]) -> String {
    let shape: Vec<(&str, usize)> = entry.iter().map(|row| (row.op.as_str(), row.args.len())).collect();
    let [dex, stats, types, catch_rate, base_exp, _dimensions, _pics, level_1_moves, growth_rate, tmhm, _padding] = entry else {
        panic!("a base-stats entry of {shape:?}")
    };
    assert!(
        matches!(shape[..], [("db", 1), ("db", 5), ("db", 2), ("db", 1), ("db", 1), ("INCBIN", 3), ("dw", 2), ("db", 4), ("db", 1), ("tmhm", _), ("db", 1)]),
        "a base-stats entry of {shape:?}",
    );
    let bytes = |row: &Row| format!("{:?}", row.args.iter().map(|arg| asm.byte(arg)).collect::<Vec<_>>());
    // Mew sets `UNUSED`, the flag past the last machine, which names no move and nothing reads.
    let machines: Vec<u8> = tmhm.args.iter().filter(|&arg| arg != "UNUSED").map(|arg| asm.byte(arg)).collect();
    format!(
        "BaseStats {{ dex: {}, stats: {}, types: {}, catch_rate: {}, base_exp: {}, level_1_moves: {}, growth_rate: {}, tm_hm: &{:?} }}",
        asm.byte(&dex.args[0]), bytes(stats), bytes(types), asm.byte(&catch_rate.args[0]), asm.byte(&base_exp.args[0]),
        bytes(level_1_moves), asm.byte(&growth_rate.args[0]), machines,
    )
}

/// An `EvosMoves` entry: evolutions to a 0, then `level, move` pairs to a 0.
fn evos_moves(asm: &Asm, stream: &[u8]) -> String {
    let [level, item, trade] = ["EVOLVE_LEVEL", "EVOLVE_ITEM", "EVOLVE_TRADE"].map(|name| asm.eval(name) as u8);
    let mut bytes = stream.iter().copied();
    let mut next = || bytes.next().expect("an evos-moves entry ends early");
    let mut evolutions = Vec::new();
    loop {
        evolutions.push(match next() {
            0 => break,
            kind if kind == level => format!("Evolution::Level {{ level: {}, into: {} }}", next(), next()),
            kind if kind == item => format!("Evolution::Item {{ item: {}, min_level: {}, into: {} }}", next(), next(), next()),
            kind if kind == trade => format!("Evolution::Trade {{ min_level: {}, into: {} }}", next(), next()),
            kind => panic!("evolution type {kind}"),
        });
    }
    let mut learnset = Vec::new();
    loop {
        match next() {
            0 => break,
            level => learnset.push(format!("({level}, {})", next())),
        }
    }
    assert!(bytes.next().is_none(), "an evos-moves entry runs on past its end");
    format!("EvosMoves {{ evolutions: &[{}], learnset: &[{}] }}", evolutions.join(", "), learnset.join(", "))
}

/// The rows before the last, a `db` whose first byte is `end`.
fn terminated(asm: &Asm, rows: &[Row], op: &str, end: u8) -> Vec<Vec<u8>> {
    let (last, rows) = rows.split_last().expect("an empty list");
    assert_eq!((last.op.as_str(), asm.byte(&last.args[0])), ("db", end), "{last:?} ends the list");
    bytes(asm, rows, op)
}

/// `RGB r,g,b, ...`: one RGB555 word per triple, laid out as `B_COLOR_*` says.
fn rgb(asm: &Asm, row: &Row) -> [u16; 4] {
    assert_eq!((row.op.as_str(), row.args.len()), ("RGB", 12), "{row:?}");
    let shifts = ["B_COLOR_RED", "B_COLOR_GREEN", "B_COLOR_BLUE"].map(|name| asm.eval(name));
    std::array::from_fn(|colour| {
        (0..3).map(|channel| asm.eval(&row.args[colour * 3 + channel]) << shifts[channel]).sum::<i64>() as u16
    })
}

fn singles(stream: Vec<u8>) -> Vec<Vec<u8>> {
    stream.into_iter().map(|byte| vec![byte]).collect()
}

/// Rows of one byte as `&[u8]`, and of more as tuples, which must all be one width.
fn list(out: &mut String, name: &str, rows: Vec<Vec<u8>>) {
    let width = rows.first().map_or(1, Vec::len);
    assert!(rows.iter().all(|row| row.len() == width), "{name}'s rows differ in width");
    let (ty, items): (String, Vec<String>) = if width == 1 {
        ("u8".to_string(), rows.iter().map(|row| row[0].to_string()).collect())
    } else {
        (format!("({})", vec!["u8"; width].join(", ")), rows.iter().map(|row| format!("({})", row.iter().map(u8::to_string).collect::<Vec<_>>().join(", "))).collect())
    };
    writeln!(out, "pub const {name}: &[{ty}] = &[{}];", items.join(", ")).unwrap();
}

fn array(out: &mut String, name: &str, ty: &str, items: Vec<String>) {
    writeln!(out, "pub const {name}: [{ty}; {}] = [{}];", items.len(), items.join(", ")).unwrap();
}

