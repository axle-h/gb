/// A `data/maps/names.asm` name, as a Rust string literal.
fn map_name(asm: &mut Asm, label: &str) -> String {
    let [row] = &asm.rows("data/maps/names.asm", label)[..] else { panic!("{label}") };
    assert_eq!((row.op.as_str(), row.args.len()), ("db", 1), "{row:?}");
    format!("{:?}", text(&row.args[0]).strip_suffix('@').expect("a terminated name"))
}

/// `rows` up to the `db "@"` that ends them.
fn until_at(rows: &[Row]) -> &[Row] {
    let (end, rows) = rows.split_last().expect("an empty list");
    assert_eq!((end.op.as_str(), end.args.as_slice()), ("db", &["\"@\"".to_string()][..]), "{end:?} ends the list");
    rows
}

/// A `dw` row's one argument.
fn word(row: &Row) -> &str {
    assert_eq!((row.op.as_str(), row.args.len()), ("dw", 1), "{row:?}");
    &row.args[0]
}

/// The byte stream after each local label in `rows`, which start with one; `.name` with or without
/// its colon, as rgbasm takes either.
fn local_streams(asm: &Asm, rows: &[Row]) -> std::collections::HashMap<String, Vec<u8>> {
    let mut streams = std::collections::HashMap::new();
    let mut current = None;
    for row in rows {
        if row.op.starts_with('.') && row.args.is_empty() {
            current = Some(row.op.trim_end_matches(':').to_string());
            streams.insert(current.clone().unwrap(), Vec::new());
            continue;
        }
        assert_eq!(row.op, "db", "{row:?}");
        streams.get_mut(current.as_ref().expect("a stream before its label")).unwrap().extend(row.args.iter().map(|arg| asm.byte(arg)));
    }
    streams
}

/// A run-length list, `db press, count` rows to a `db -1`, as its pairs.
fn rle(asm: &Asm, rows: &[Row]) -> Vec<(u8, u8)> {
    let mut stream = bytes(asm, rows, "db").concat();
    assert_eq!(stream.pop(), Some(0xFF), "a run-length list ends in -1");
    stream.chunks_exact(2).map(|pair| (pair[0], pair[1])).collect()
}

/// A `db` string, `next` lines and all, as `Chars`: its text in charmap spelling and its bytes
/// given by number, the `@` that ends it included. It stops at a label an `INCLUDE` reads in, or
/// at the first statement that is not a string. `#NAME` is the `EQUS` string it names.
fn db_string(asm: &Asm, rows: &[Row]) -> Vec<String> {
    rows.iter().take_while(|row| !is_label(row) && matches!(row.op.as_str(), "db" | "next")).flat_map(|row| {
        let lead = (row.op == "next").then(|| "Chars::Text(\"<NEXT>\")".to_string());
        lead.into_iter().chain(row.args.iter().map(|arg| match (arg.strip_prefix('#'), arg.starts_with('"')) {
            (Some(name), _) => format!("Chars::Text({:?})", asm.equs(name).unwrap_or_else(|| panic!("no string {name}"))),
            (None, true) => format!("Chars::Text({:?})", text(arg)),
            (None, false) => format!("Chars::Byte({})", asm.byte(arg)),
        }))
    }).collect()
}

