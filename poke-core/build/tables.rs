/// Map-indexed headers from `MapHeaderPointers`, `None` where a map borrows another's header. Each
/// is its `data/maps/headers/` file, the blocks `maps.asm` puts under its `_Blocks` label and the
/// events of its `data/maps/objects/` file.
fn maps(asm: &mut Asm, out: &mut String) {
    let pointers = asm.rows("data/maps/map_header_pointers.asm", "MapHeaderPointers");
    assert_eq!(pointers.len() as i64, asm.eval("NUM_MAPS"));
    let names: Vec<&str> = pointers.iter().map(|row| {
        assert_eq!((row.op.as_str(), row.args.len()), ("dw", 1), "{row:?}");
        row.args[0].strip_suffix("_h").unwrap_or_else(|| panic!("{row:?} names no header"))
    }).collect();
    let blocks = BlockFiles::read(asm);
    let dir = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("maps");
    std::fs::create_dir_all(&dir).unwrap();
    let items = names.iter().enumerate().map(|(id, &name)| {
        let rows = asm.file_rows(&format!("data/maps/headers/{name}.asm"));
        let [header, connections @ .., end] = &rows[..] else { panic!("{name}'s header is {rows:?}") };
        assert_eq!((header.op.as_str(), header.args.len(), header.args[0].as_str(), end.op.as_str()),
            ("map_header", 3, name, "end_map_header"), "{name}'s header");
        // A header is its own map's, or failing that the one map that names it; any other map naming
        // it borrows it.
        let constant = &header.args[1];
        let own = asm.eval(constant) as usize;
        let owner = if names.get(own) == Some(&name) { own } else {
            let users: Vec<usize> = (0..names.len()).filter(|&i| names[i] == name).collect();
            assert_eq!(users.len(), 1, "{name} is shared, and by none of its own");
            users[0]
        };
        if owner != id {
            return "None".to_string();
        }
        let (width, height) = (asm.byte(&format!("{constant}_WIDTH")), asm.byte(&format!("{constant}_HEIGHT")));
        let connections: Vec<String> = connections.iter().map(|row| {
            assert_eq!((row.op.as_str(), row.args.len()), ("connection", 4), "{name}: {row:?}");
            let map = asm.eval(&row.args[2]) as usize;
            assert_eq!(names[map], row.args[1], "{name}: {row:?} names another map's blocks");
            format!("Connection {{ direction: {}, map: {map}, offset: {} }}", asm.byte(&row.args[0].to_ascii_uppercase()), i8::try_from(asm.eval(&row.args[3])).unwrap())
        }).collect();
        let bytes = blocks.bytes(asm, &format!("{name}_Blocks"), width as usize * height as usize);
        std::fs::write(dir.join(format!("{name}.blk")), bytes).unwrap();
        format!(
            "Some(MapHeader {{ name: {name:?}, tileset: {}, height: {height}, width: {width}, connections: &[{}], \
             blocks: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/maps/{name}.blk\")), objects: {} }})",
            asm.byte(&header.args[2]), connections.join(", "), map_objects(asm, name, constant),
        )
    }).collect();
    array(out, "MAP_HEADERS", "Option<MapHeader>", items);
}

/// `maps.asm`'s `INCBIN`s in order, each with its `SECTION`, and the index each `_Blocks` label
/// names: a label with no `INCBIN` of its own shares the next one's.
struct BlockFiles {
    incbins: Vec<(usize, String)>,
    labels: std::collections::HashMap<String, usize>,
}

impl BlockFiles {
    fn read(asm: &Asm) -> Self {
        let (mut incbins, mut labels, mut pending, mut section) = (Vec::new(), std::collections::HashMap::new(), Vec::new(), 0);
        for line in asm.lines("maps.asm") {
            let (label, rest) = line.split_once(':').unwrap_or(("", &line));
            if rest.trim_start().starts_with("SECTION") {
                section += 1;
            }
            if label.ends_with("_Blocks") {
                pending.push(label.trim().to_string());
            }
            if let Some(file) = rest.trim().strip_prefix("INCBIN") {
                labels.extend(pending.drain(..).map(|label| (label, incbins.len())));
                incbins.push((section, file.trim().trim_matches('"').to_string()));
            }
        }
        assert!(pending.is_empty(), "{pending:?} name no INCBIN");
        BlockFiles { incbins, labels }
    }

    /// The `size` bytes from `label`. A `.blk` shorter than its map reads on into the next `INCBIN`
    /// in its section, which the source fixes: `UndergroundPathNorthSouth`'s last row is
    /// `UndergroundPathWestEast`'s first.
    fn bytes(&self, asm: &Asm, label: &str, size: usize) -> Vec<u8> {
        let &first = self.labels.get(label).unwrap_or_else(|| panic!("no {label} in maps.asm"));
        let mut bytes = Vec::new();
        for (section, file) in &self.incbins[first..] {
            assert_eq!(*section, self.incbins[first].0, "{label} runs off the end of its section");
            bytes.extend(std::fs::read(asm.path(file)).unwrap());
            if bytes.len() >= size {
                bytes.truncate(size);
                return bytes;
            }
        }
        panic!("{label} runs off the end of maps.asm")
    }
}

/// A map's `_Object` label: the border block, then its warps, signs and objects. What follows
/// `def_warps_to` is the `warp_to` rows it generates from the warps, and in a few maps a stray row or
/// two the code never reads.
fn map_objects(asm: &mut Asm, name: &str, constant: &str) -> String {
    // `object_const_def` then `const_export`s, one per object and in the order written, which
    // `toggleable_objects.asm` names objects by.
    let file = format!("data/maps/objects/{name}.asm");
    let mut next = None;
    for row in asm.file_rows(&file) {
        match row.op.as_str() {
            "object_const_def" => next = Some(1),
            "const_export" => {
                let value = next.expect("a const_export before its object_const_def");
                asm.set(&row.args[0], value);
                next = Some(value + 1);
            }
            _ => {}
        }
    }
    let rows = asm.rows(&format!("data/maps/objects/{name}.asm"), &format!("{name}_Object"));
    let mut rows = rows.iter().peekable();
    let border = rows.next().expect("no border block");
    assert_eq!((border.op.as_str(), border.args.len()), ("db", 1), "{name}: {border:?}");
    let mut section = |start: &str, op: &str| -> Vec<Vec<String>> {
        let row = rows.next().unwrap_or_else(|| panic!("{name} has no {start}"));
        assert_eq!(row.op, start, "{name}: {row:?}");
        std::iter::from_fn(|| rows.next_if(|row| row.op == op)).map(|row| row.args.clone()).collect()
    };
    let (warps, signs, objects) = (section("def_warp_events", "warp_event"), section("def_bg_events", "bg_event"), section("def_object_events", "object_event"));
    let end = rows.next().unwrap_or_else(|| panic!("{name} has no def_warps_to"));
    // The `warp_to` rows are computed from this map's width, which is the header's.
    assert_eq!((end.op.as_str(), end.args.len()), ("def_warps_to", 1), "{name}");
    assert_eq!(asm.eval(&format!("{}_WIDTH", end.args[0])), asm.eval(&format!("{constant}_WIDTH")), "{name}");
    assert!(rows.all(|row| row.op == "warp_to" || row.op == "db"), "{name} runs on past its def_warps_to");
    let warps: Vec<String> = warps.iter().map(|args| {
        let [x, y, map, warp] = [0, 1, 2, 3].map(|i| asm.byte(&args[i]));
        format!("WarpEvent {{ x: {x}, y: {y}, map: {map}, warp: {warp} }}")
    }).collect();
    let signs: Vec<String> = signs.iter().map(|args| {
        let [x, y, text_id] = [0, 1, 2].map(|i| asm.byte(&args[i]));
        format!("BgEvent {{ x: {x}, y: {y}, text_id: {text_id} }}")
    }).collect();
    let objects: Vec<String> = objects.iter().map(|args| {
        let [x, y, sprite, movement, range_or_direction, text_id] = [0, 1, 2, 3, 4, 5].map(|i| asm.byte(&args[i]));
        let kind = match args.len() {
            6 => "Person".to_string(),
            7 => format!("Item({})", asm.byte(&args[6])),
            8 => format!("Trainer {{ class: {}, number: {} }}", asm.byte(&args[6]), asm.byte(&args[7])),
            _ => panic!("{name}: object_event {args:?}"),
        };
        format!("ObjectEvent {{ x: {x}, y: {y}, sprite: {sprite}, movement: {movement}, range_or_direction: {range_or_direction}, text_id: {text_id}, kind: crate::map_objects::ObjectKind::{kind} }}")
    }).collect();
    format!("MapObjects {{ border_block: {}, warps: &[{}], signs: &[{}], objects: &[{}] }}",
        asm.byte(&border.args[0]), warps.join(", "), signs.join(", "), objects.join(", "))
}

