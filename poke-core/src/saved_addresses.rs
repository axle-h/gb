#[cfg(test)]
mod tests {
    use super::*;
    use crate::tables::{HiddenRoutine, DEX_RATINGS, TEXT_POINTERS, TRAINER_HEADERS};
    use crate::text_script::SavedText;

    /// Every label a header, a text pointer table, a hidden routine or a trainer's end-of-battle
    /// text can be has its address, and a saved text held by address loads as its label.
    #[test]
    fn every_label_a_save_types_holds_has_its_address() {
        let has = |label: &str| SAVED_ADDRESSES.iter().any(|&(_, name)| name == label);
        for &(_, table, trainers) in TRAINER_HEADERS {
            assert!(has(table), "{table}");
            for trainer in trainers {
                assert!(has(trainer.label) && has(trainer.end_battle), "{}", trainer.label);
            }
        }
        for label in TEXT_POINTERS.iter().map(|&(label, _)| label).chain(HiddenRoutine::LABELS).chain(DEX_RATINGS.map(|(_, label)| label)) {
            assert!(has(label), "{label}");
        }
        let old = rmp_serde::to_vec_named(&rom(0x18, 0x518F)).unwrap();
        assert_eq!(rmp_serde::from_slice::<SavedText>(&old).unwrap(), SavedText("ViridianForestYoungster2EndBattleText"));
    }
}
